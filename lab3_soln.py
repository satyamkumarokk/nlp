from sklearn.datasets import fetch_20newsgroups

"""Cell **2**"""

# Select two domains

categories = [
    "sci.space",
    "comp.graphics"
]

# Load dataset

newsgroups_data = fetch_20newsgroups(
    subset='train',
    categories=categories,
    remove=('headers', 'footers', 'quotes')
)

print("Number of Documents:", len(newsgroups_data.data))

"""Cell 3: Extract Domain **Terms**"""

# Combine all documents

all_text = " ".join(
    newsgroups_data.data
)

# Convert to lowercase
# Extract words

words_list = re.findall(
    r'\b[a-zA-Z]{3,}\b',
    all_text.lower()
)

print("Total Words Extracted:", len(words_list))

"""Cell 4: Remove **Stopwords**"""

nltk.download('stopwords')

from nltk.corpus import stopwords

stop_words = set(
    stopwords.words('english')
)

filtered_words = [
    word
    for word in words_list
    if word not in stop_words
]

"""Cell 5: Top 20 Domain **Terms**"""

word_frequency = Counter(
    filtered_words
)

top_20_terms = word_frequency.most_common(20)

domain_df = pd.DataFrame(
    top_20_terms,
    columns=[
        "Domain Term",
        "Frequency"
    ]
)

domain_df

