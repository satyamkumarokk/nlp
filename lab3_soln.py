import nltk
import pandas as pd
import math
import re

from collections import Counter
from nltk.corpus import brown
from nltk.tokenize import word_tokenize
from nltk.util import ngrams

nltk.download('brown')
nltk.download('punkt')
nltk.download('punkt_tab')

"""Cell 2: Load Brown News **Corpus**"""

# Load Brown Corpus - News category
news_words = brown.words(categories='news')

# Select at least 5000 tokens
news_words = news_words[:5000]

# Basic preprocessing
cleaned_words = [
    word.lower()
    for word in news_words
    if word.isalpha()
]

print("Total Tokens:", len(cleaned_words))
print("Vocabulary Size:", len(set(cleaned_words)))

"""Cell 3: Generate Unigram, Bigram and **Trigram**"""

# Generate N-grams

unigrams = list(ngrams(cleaned_words, 1))
bigrams = list(ngrams(cleaned_words, 2))
trigrams = list(ngrams(cleaned_words, 3))

# Frequency counts

unigram_freq = Counter(unigrams)
bigram_freq = Counter(bigrams)
trigram_freq = Counter(trigrams)

"""Cell 4: Top 10 **Unigrams**"""

top_unigrams = unigram_freq.most_common(10)

unigram_df = pd.DataFrame(
    top_unigrams,
    columns=["Unigram", "Frequency"]
)

unigram_df

