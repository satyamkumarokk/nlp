"""# **Task 2 — Bigram Language Model**

Cell 1: Load Gutenberg **Corpus**
"""

nltk.download('gutenberg')

from nltk.corpus import gutenberg

# Load English text
emma_words = gutenberg.words('austen-emma.txt')

# Select a portion of the corpus
emma_words = emma_words[:10000]

# Tokenize and normalize
cleaned_emma = [
    word.lower()
    for word in emma_words
    if word.isalpha()
]

print("Total Tokens:", len(cleaned_emma))
print("Vocabulary Size:", len(set(cleaned_emma)))

"""Cell 2: Unigram and Bigram **Counts**"""

# Unigram frequency
unigram_counts = Counter(cleaned_emma)

# Bigram frequency
bigram_counts = Counter(
    ngrams(cleaned_emma, 2)
)

# Vocabulary size
V = len(unigram_counts)

print("Number of Unigrams:", len(unigram_counts))
print("Number of Bigrams:", len(bigram_counts))

"""Cell 3: Add-One **Smoothing**"""

def bigram_probability(previous_word, current_word):

    bigram_count = bigram_counts[
        (previous_word, current_word)
    ]

    previous_count = unigram_counts[
        previous_word
    ]

    probability = (
        (bigram_count + 1)
        / (previous_count + V)
    )

    return probability

"""Cell 4: Sentence **Score**"""

def sentence_score(sentence):

    words = [
        word.lower()
        for word in word_tokenize(sentence)
        if word.isalpha()
    ]

    score = 0

    for i in range(1, len(words)):

        probability = bigram_probability(
            words[i-1],
            words[i]
        )

        score += math.log(probability)

    return score

"""Cell 5: Test 3 **Sentences**"""

test_sentences = [
    "The woman was happy",
    "The man went home",
    "She reads a good book"
]

for sentence in test_sentences:

    score = sentence_score(sentence)

    print("Sentence:", sentence)
    print("Score:", score)
    print()

